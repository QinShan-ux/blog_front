  allTags = computed(() => {
    const tagSet = new Set<string>();
    this.essays.forEach(e => e.tags.forEach(t => tagSet.add(t)));
    return [...tagSet];
  });

  filteredEssays = computed(() => {
    const tag = this.selectedTag();
    if (!tag) return this.essays;
    return this.essays.filter(e => e.tags.includes(tag));
  });

  essayCount = computed(() => this.essays.length);

  tagCount = computed(() => this.allTags().length);

  latestDate = computed(() => this.essays[0]?.date ?? '');

  selectTag(tag: string) {
    this.selectedTag.set(this.selectedTag() === tag ? null : tag);
  }

  clearTag() {
    this.selectedTag.set(null);
  }

  toggleExpand(id: number) {
    this.expandedId.set(this.expandedId() === id ? null : id);
  }

  isExpanded(id: number): boolean {
    return this.expandedId() === id;
  }

  getMonthLabel(date: string): string {
    const d = new Date(date);
    const months = ['一月', '二月', '三月', '四月', '五月', '六月',
                    '七月', '八月', '九月', '十月', '十一月', '十二月'];
    return months[d.getMonth()];
  }

  getDayOfMonth(date: string): string {
    return new Date(date).getDate().toString();
  }

  getWeekday(date: string): string {
    const days = ['周日', '周一', '周二', '周三', '周四', '周五', '周六'];
    return days[new Date(date).getDay()];
  }
